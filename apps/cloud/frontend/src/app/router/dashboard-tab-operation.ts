/**
 * 控制台标签切换与关闭操作的状态标记。
 *
 * 标签关闭/关闭其他等操作需要「先导航、导航成功后再落标签状态」，
 * 这段时间内路由变化不应再触发标签同步，否则会把即将删除的标签内容写回。
 */

/** 是否正在执行关闭类标签操作。 */
let 标签操作进行中 = false

/** 标记开始执行关闭类标签操作。 */
export function 开始控制台标签操作(): void {
  标签操作进行中 = true
}

/** 标记关闭类标签操作结束。 */
export function 结束控制台标签操作(): void {
  标签操作进行中 = false
}

/** 判断当前是否正在执行关闭类标签操作。 */
export function 是否控制台标签操作进行中(): boolean {
  return 标签操作进行中
}
